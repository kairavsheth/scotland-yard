// ─── Build adjacency map ──────────────────────────────────────────────────────

function buildGraph(): Map<number, Station> {
  const map = new Map<number, Station>();

  for (const [id, x, y] of RAW_STATIONS) {
    map.set(id, { id, x, y, taxi: [], bus: [], underground: [], water: [] });
  }

  for (const [a, b, t] of EDGES) {
    const sa = map.get(a)!;
    const sb = map.get(b)!;
    if (!sa[t].includes(b)) sa[t].push(b);
    if (t !== "water" && !sb[t].includes(a)) sb[t].push(a); // ferry is one-way only for display; Mr. X can go either direction
  }

  // Make ferry bidirectional for movement
  const ferryEdges = EDGES.filter(([, , t]) => t === "water");
  for (const [a, b] of ferryEdges) {
    const sb = map.get(b)!;
    if (!sb.water.includes(a)) sb.water.push(a);
  }

  return map;
}

export const BOARD: Map<number, Station> = buildGraph();

export function getStation(id: number): Station {
  const s = BOARD.get(id);
  if (!s) throw new Error(`Unknown station ${id}`);
  return s;
}

/** Returns stations reachable from `from` by the given transport type */
export function getReachable(from: number, transport: Transport): number[] {
  const s = BOARD.get(from);
  if (!s) return [];
  return s[transport];
}

/** All stations reachable from `from` (including via black ticket = all transports) */
export function getAllReachable(from: number, includeWater = false): Map<Transport, number[]> {
  const s = BOARD.get(from);
  if (!s) return new Map();
  const result = new Map<Transport, number[]>([
    ["taxi", s.taxi],
    ["bus", s.bus],
    ["underground", s.underground],
  ]);
  if (includeWater) result.set("water", s.water);
  return result;
}

